// Writes .env.test.local and .env.local from a running local Supabase stack,
// so the test suite and the dev server both point at it without hand-copying
// keys out of the `supabase start` banner.
//
// Usage: npm run db:env   (after `npm run db:start`)

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

function status() {
  try {
    return execFileSync('npx', ['supabase', 'status', '-o', 'env'], {
      encoding: 'utf8',
      shell: process.platform === 'win32',
    });
  } catch {
    console.error('Could not read local Supabase status.');
    console.error('Is the stack running? Try: npm run db:start');
    process.exit(1);
  }
}

const raw = status();
const vars = Object.fromEntries(
  raw.split('\n').filter(Boolean).map((line) => {
    const i = line.indexOf('=');
    return [line.slice(0, i).trim(), line.slice(i + 1).trim().replace(/^"|"$/g, '')];
  })
);

const apiUrl = vars.API_URL;
const anon = vars.ANON_KEY;
const service = vars.SERVICE_ROLE_KEY;
const dbUrl = vars.DB_URL;

if (!apiUrl || !anon || !service) {
  console.error('Local Supabase status did not include the expected keys.');
  console.error('Got:', Object.keys(vars).join(', '));
  process.exit(1);
}

writeFileSync('.env.test.local', [
  '# Generated by npm run db:env. Local stack only — safe to delete.',
  `SUPABASE_URL=${apiUrl}`,
  `SUPABASE_ANON_KEY=${anon}`,
  `SUPABASE_SERVICE_ROLE_KEY=${service}`,
  `SUPABASE_DB_URL=${dbUrl ?? 'postgresql://postgres:postgres@127.0.0.1:54322/postgres'}`,
  '',
].join('\n'));

writeFileSync('.env.local', [
  '# Generated by npm run db:env. Points the dev server at local Supabase.',
  `VITE_SUPABASE_URL=${apiUrl}`,
  `VITE_SUPABASE_ANON_KEY=${anon}`,
  '',
].join('\n'));

console.log('Wrote .env.test.local and .env.local for the local stack.');
console.log(`  API: ${apiUrl}`);
console.log('The test suite now targets local. Delete .env.test.local to go back to hosted.');
